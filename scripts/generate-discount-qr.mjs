// Offline generator for QR discount codes. Touches no database and no network.
//
// Run:
//   node scripts/generate-discount-qr.mjs --base-url https://<production-origin>
//
// Output (scripts/output/, git-ignored, NEVER commit it):
//   qr/<NN>-<CODE>.png     one QR per code
//   codes.csv              index, code, url, png file, base url
//   insert-codes.sql       INSERT for "codigosDescuento" (event 101, 15%)
//
// Codes are uppercase only because the DB lookup is `codigo = upper(trim(p_codigo))`.
import { randomInt } from "node:crypto";
import { mkdir, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

export const EVENT_ID = 101;
export const PERCENTAGE = 15;
export const CODE_COUNT = 40;
export const CODE_LENGTH = 10;
// Unambiguous uppercase alphabet: no I, L, O, 0, 1.
export const ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";

export function parseBaseUrl(raw) {
  if (!raw || typeof raw !== "string") {
    throw new Error("--base-url is required (absolute https origin, e.g. https://example.com). There is no default.");
  }
  let url;
  try {
    url = new URL(raw);
  } catch {
    throw new Error(`--base-url is not a valid absolute URL: ${raw}`);
  }
  if (url.protocol !== "https:") throw new Error("--base-url must use https://");
  if (url.username || url.password) throw new Error("--base-url must not contain credentials");
  if (url.search || url.hash || (url.pathname !== "/" && url.pathname !== "")) {
    throw new Error("--base-url must be an origin only (no path, query or hash)");
  }
  return url.origin; // no trailing slash
}

export function generateCodes(count = CODE_COUNT, length = CODE_LENGTH) {
  const codes = new Set();
  while (codes.size < count) {
    let code = "";
    for (let i = 0; i < length; i++) code += ALPHABET[randomInt(ALPHABET.length)];
    codes.add(code);
  }
  return [...codes];
}

export function buildUrl(base, code) {
  return `${base}/eventos/${EVENT_ID}?code=${code}`;
}

function csvCell(value) {
  const s = String(value);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function buildCsv(rows, base) {
  const lines = ["index,code,url,png,base_url"];
  for (const r of rows) {
    lines.push([r.index, r.code, r.url, r.png, base].map(csvCell).join(","));
  }
  return lines.join("\n") + "\n";
}

export function buildInsertSql(codes) {
  const values = codes.map((c) => `  ('${c}', false, ${EVENT_ID}, ${PERCENTAGE})`).join(",\n");
  return [
    "-- Generated by scripts/generate-discount-qr.mjs. Do NOT commit.",
    `INSERT INTO "codigosDescuento" (codigo, acreditado, "idEvento", porcentaje) VALUES`,
    values + ";",
    ""
  ].join("\n");
}

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--base-url") args.baseUrl = argv[++i];
    else if (a.startsWith("--base-url=")) args.baseUrl = a.slice("--base-url=".length);
    else throw new Error(`Unknown argument: ${a}`);
  }
  return args;
}

async function main() {
  const { baseUrl } = parseArgs(process.argv.slice(2));
  const base = parseBaseUrl(baseUrl);

  const here = path.dirname(fileURLToPath(import.meta.url));
  const outDir = path.join(here, "output");
  const qrDir = path.join(outDir, "qr");
  await rm(outDir, { recursive: true, force: true });
  await mkdir(qrDir, { recursive: true });

  const codes = generateCodes();
  const rows = [];
  for (let i = 0; i < codes.length; i++) {
    const code = codes[i];
    const index = String(i + 1).padStart(2, "0");
    const url = buildUrl(base, code);
    const png = `qr/${index}-${code}.png`;
    await QRCode.toFile(path.join(outDir, png), url, { type: "png", errorCorrectionLevel: "M", width: 600, margin: 2 });
    rows.push({ index, code, url, png });
  }

  await writeFile(path.join(outDir, "codes.csv"), buildCsv(rows, base), "utf8");
  await writeFile(path.join(outDir, "insert-codes.sql"), buildInsertSql(codes), "utf8");

  console.log(`Generated ${codes.length} codes in ${outDir}`);
  console.log("Output is git-ignored. Review insert-codes.sql before running it manually.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
