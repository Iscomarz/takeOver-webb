    <h1>Politica de Privacidad</h1>

<h3>¿Qué datos personales recopilamos y por qué los recopilamos?</h3>

<p>Última actualización: 02/24/2025

    En Take Over, nos comprometemos a proteger la privacidad de nuestros usuarios. Esta política de privacidad explica qué datos recopilamos, cómo los usamos y los derechos de los usuarios respecto a su información personal.
    
    1. Datos que Recopilamos
    
    Al realizar una compra de boletos en nuestro sitio, recopilamos la siguiente información:
    - Nombre
    - Correo electrónico
    
    No recopilamos información bancaria, ya que los pagos son procesados de manera segura a través de Stripe.
    
    2. Uso de los Datos
    
    La información proporcionada se utiliza exclusivamente para:
    Generar y enviar boletos en formato PDF al correo electrónico del comprador.
    Almacenar información sobre las compras para futuras referencias y estadísticas internas.
    Reenviar boletos en caso de ser necesario.
    
    No enviamos correos promocionales ni boletines informativos.
    
    3. Compartición de Datos
    
    No compartimos información personal con terceros. Stripe procesa los pagos directamente y no recibimos datos bancarios de los usuarios.
    
    4. Seguridad de los Datos
    
    La información de los usuarios se almacena en una base de datos segura en Supabase, que cuenta con cifrado y autenticación para proteger la integridad de los datos.
    
    5. Derechos de los Usuarios
    
    Los usuarios pueden solicitar la modificación del nombre en la compra de su boleto.
    No se permiten reembolsos, salvo en caso de cancelación total del evento, en cuyo caso se ofrecerá la devolución completa del importe o la posibilidad de usar el monto para un evento futuro.
    Si tienes dudas sobre esta política, puedes contactarnos en take.oover.show@gmail.com.
    
    </p>
